import 'dart:async';
import 'dart:convert';

import 'package:audioplayers/audioplayers.dart';
import 'package:flutter/foundation.dart';
import 'package:http/http.dart' as http;

import '../config.dart';
import 'voice_service.dart';

/// Plays audio. Wraps the audio player package so tests can use a fake.
abstract class AudioOutput {
  /// Starts playing [wav]; completes once playback has started.
  Future<void> play(Uint8List wav, {double rate = 1.0});
  Future<void> stop();
}

/// audioplayers works on web, Android, iOS, macOS, Windows and Linux.
class AudioplayersOutput implements AudioOutput {
  // Created on first use, so building the service doesn't touch the platform.
  AudioPlayer? _player;

  @override
  Future<void> play(Uint8List wav, {double rate = 1.0}) async {
    final player = _player ??= await _createPlayer();
    await player.stop();
    await player.setSource(BytesSource(wav, mimeType: 'audio/wav'));
    // Changes speed without changing pitch on every platform.
    await player.setPlaybackRate(rate);
    await player.resume();
  }

  @override
  Future<void> stop() async => _player?.stop();

  static Future<AudioPlayer> _createPlayer() async {
    final player = AudioPlayer();
    // The default (release) mode discards the web audio element on stop, and the
    // replacement starts at normal speed, so "Hear again" would ignore the slow rate.
    await player.setReleaseMode(ReleaseMode.stop);
    return player;
  }
}

class _SessionEnded implements Exception {}

class _ServerVoiceFailed implements Exception {
  _ServerVoiceFailed(this.reason);
  final String reason;
  @override
  String toString() => reason;
}

/// Reads aloud with a real Kinyarwanda voice generated by the backend
/// (POST /api/tts, which calls the TTS service in tts/). If the server can't
/// produce it (no TTS service, a timeout, no connection), [fallback] reads
/// aloud instead and the learner gets a short notice.
class RemoteVoiceService implements VoiceService {
  RemoteVoiceService({
    required this.baseUrl,
    required this.accessToken,
    required this.onUnauthorized,
    required this.fallback,
    AudioOutput? output,
    http.Client? client,
    @visibleForTesting this.timeout = const Duration(seconds: 30),
    @visibleForTesting this.retryAfter = const Duration(minutes: 1),
  })  : _output = output ?? AudioplayersOutput(),
        _client = client ?? http.Client() {
    fallback.problems.listen(_problems.add);
  }

  final String baseUrl;

  /// The signed-in user's token, sent as `Authorization: Bearer <token>`.
  final Future<String?> Function() accessToken;

  /// Called when the backend rejects the token; signs the user out.
  final Future<void> Function() onUnauthorized;

  /// Reads aloud when the server's voice can't.
  final VoiceService fallback;

  /// How long to wait for the server's audio before using [fallback]. On CPU the
  /// server takes about as long to generate speech as to play it.
  final Duration timeout;

  /// After the server fails, use [fallback] straight away for this long rather
  /// than make the learner wait on a server that is down.
  final Duration retryAfter;

  final AudioOutput _output;
  final http.Client _client;

  /// Recent audio by text, so "Hear again" plays instantly. Oldest first.
  final _cache = <String, Uint8List>{};
  static const _cacheEntries = 40;

  final _problems = StreamController<String>.broadcast();
  final _preparing = ValueNotifier<String?>(null);
  int _request = 0;
  bool _usedFallback = false;
  bool _toldAboutFallback = false;
  DateTime? _serverDownUntil;
  String? _model;

  @override
  VoiceQuality get quality => _usedFallback ? fallback.quality : VoiceQuality.kinyarwanda;

  @override
  VoiceInfo? get voice => _usedFallback
      ? fallback.voice
      : VoiceInfo(
          name: 'Kinyarwanda voice from the Tuganire server${_model == null ? '' : ' ($_model)'}',
          locale: 'rw',
          quality: VoiceQuality.kinyarwanda,
          voiceCount: null);

  @override
  Stream<String> get problems => _problems.stream;

  @override
  ValueListenable<String?> get preparing => _preparing;

  /// Gets the device voice ready too, in case the server's voice fails.
  @override
  Future<void> init() => fallback.init();

  @override
  Future<void> speak(String text, {bool slow = false}) async {
    if (text.trim().isEmpty) return;
    // Each speak() or stop() supersedes any speak() still waiting for audio.
    final request = ++_request;
    bool superseded() => request != _request;
    await _stopPlayback();

    final Uint8List audio;
    try {
      audio = await _audioFor(text, superseded);
    } on _SessionEnded {
      if (!superseded()) await onUnauthorized();
      return;
    } catch (e) {
      if (superseded()) return;
      debugPrint('Server voice failed ($e); using the device voice.');
      return _speakWithFallback(text, slow);
    }
    if (superseded()) return;

    try {
      await _output.play(audio, rate: slow ? 0.8 : 1.0);
      _usedFallback = false;
      _toldAboutFallback = false;
    } catch (e) {
      if (superseded()) return;
      debugPrint('Audio playback failed: $e');
      _problems.add('$e'.contains('NotAllowed')
          ? 'The browser blocked read aloud until you tap the page. Tap “Hear again” to play it.'
          : 'Read aloud couldn’t play. Try “Hear again”.');
    }
  }

  Future<Uint8List> _audioFor(String text, bool Function() superseded) async {
    final cached = _cache.remove(text);
    if (cached != null) return _cache[text] = cached; // now the most recent
    if (baseUrl == AppConfig.railwayUrlPlaceholder) throw _ServerVoiceFailed('no server address');
    final downUntil = _serverDownUntil;
    if (downUntil != null && DateTime.now().isBefore(downUntil)) {
      throw _ServerVoiceFailed('server failed recently');
    }

    _preparing.value = text;
    try {
      final token = await accessToken();
      if (token == null) throw _SessionEnded();
      final res = await _client
          .post(
            Uri.parse('$baseUrl/api/tts'),
            headers: {'content-type': 'application/json', 'authorization': 'Bearer $token'},
            body: jsonEncode({'text': text}),
          )
          .timeout(timeout);
      if (res.statusCode == 401) throw _SessionEnded();
      if (res.statusCode != 200) {
        // 5xx: no TTS service, or it failed. A 4xx is about this text only.
        if (res.statusCode >= 500) _serverDownUntil = DateTime.now().add(retryAfter);
        throw _ServerVoiceFailed('HTTP ${res.statusCode}');
      }
      _model = res.headers['x-tts-model'] ?? _model;
      _cache[text] = res.bodyBytes;
      if (_cache.length > _cacheEntries) _cache.remove(_cache.keys.first);
      return res.bodyBytes;
    } on TimeoutException {
      _serverDownUntil = DateTime.now().add(retryAfter);
      throw _ServerVoiceFailed('timed out');
    } on http.ClientException catch (e) {
      _serverDownUntil = DateTime.now().add(retryAfter);
      throw _ServerVoiceFailed('no connection: ${e.message}');
    } finally {
      if (!superseded()) _preparing.value = null;
    }
  }

  Future<void> _speakWithFallback(String text, bool slow) async {
    _usedFallback = true;
    if (!_toldAboutFallback) {
      _toldAboutFallback = true;
      _problems.add('The Kinyarwanda voice isn’t available right now, so your device’s voice is reading aloud.');
    }
    await fallback.speak(text, slow: slow);
  }

  @override
  Future<void> stop() {
    _request++;
    return _stopPlayback();
  }

  Future<void> _stopPlayback() async {
    _preparing.value = null;
    await Future.wait([_output.stop(), fallback.stop()]);
  }
}
